#!/usr/bin/env python3
"""Generate the Claude Code and Codex agents from the neutral sources in `.agents/agents/`.

Each source `.agents/agents/<name>.md` has a frontmatter with the agent's `name` (hyphenated),
`description`, `profile`, `effort`, `skills` (the framework skills the agent may use), a `codex`
block (`sandbox_mode`) and a `claude` block (`tools`); its body is the agent's instructions. The
profile gives the model of each environment from the table in
`.agents/config/model-profiles.md`. The script writes `.claude/agents/<name>.md` (model,
effort, tools) and `.codex/agents/<name>.toml` (model, `model_reasoning_effort`, sandbox, and
every skill of `.agents/skills/` that `skills` does not list, disabled), and `docs/catalog.md`
when it is given `--catalog` or that file already exists as a generated catalog. It rejects a
source whose `skills` differ from the framework skills named in its `# Skills` section, or whose
profile is not in the table. Files in the output folders without a source, such as a project's
own agents, are listed and never changed.

Usage: python3 .agents/scripts/generate_agents.py [--check] [--catalog] [repository-root]
  --check    write nothing; list the files that would change and exit 1 when any would.
  --catalog  also write docs/catalog.md.
Compatible with Python 3.6.
"""
import glob
import json
import os
import re
import sys

USAGE = "usage: python3 .agents/scripts/generate_agents.py [--check] [--catalog] [repository-root]"
CATALOG = os.path.join("docs", "catalog.md")
CATALOG_MARK = "<!-- Generated by .agents/scripts/generate_agents.py; do not edit. -->"
PROFILES = os.path.join(".agents", "config", "model-profiles.md")
PROFILE_COLUMNS = ["Profile", "Codex", "Claude Code"]
# Effort levels that both Codex's `model_reasoning_effort` and Claude Code's `effort` accept.
EFFORTS = ("low", "medium", "high", "xhigh")
FIELDS = {
    None: ("name", "description", "profile", "effort", "skills", "codex", "claude"),
    "codex": ("sandbox_mode",),
    "claude": ("tools",),
}


def scalar(text, where):
    """Return a frontmatter scalar without its quotes, or a flow list `[a, b]` as a list."""
    text = text.strip()
    if text.startswith("[") and text.endswith("]"):
        return [scalar(item, where) for item in text[1:-1].split(",") if item.strip()]
    if text.startswith('"'):
        try:
            return json.loads(text)
        except ValueError:
            sys.exit("error: %s: invalid quoted value %s" % (where, text))
    if text.startswith("'") and text.endswith("'") and len(text) > 1:
        return text[1:-1].replace("''", "'")
    return text


def parse_front(path):
    """Return (frontmatter, body) of a Markdown file with a restricted YAML frontmatter.

    Supported: `key: value` pairs, flow lists `[a, b]`, and top-level keys without a value
    followed either by a block list of scalars (`  - item`) or by one level of nested
    `key: value` pairs, indented by two spaces.
    """
    with open(path) as fh:
        text = fh.read()
    match = re.match(r"---[ \t]*\n(.*?)\n---[ \t]*\n", text, re.S)
    if not match:
        sys.exit("error: %s: no frontmatter" % path)
    front, block = {}, None
    for number, line in enumerate(match.group(1).split("\n"), 2):
        where = "%s:%d" % (path, number)
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        item = re.match(r"  - (.*)$", line)
        pair = re.match(r"( {0,2})([A-Za-z_][\w-]*):(?: (.*))?$", line)
        if item and block is not None and isinstance(front[block], list):
            front[block].append(scalar(item.group(1), where))
        elif item and block is not None and front[block] is None:
            front[block] = [scalar(item.group(1), where)]
        elif pair and not pair.group(1):
            block = None if pair.group(3) else pair.group(2)
            front[pair.group(2)] = scalar(pair.group(3), where) if pair.group(3) else None
        elif pair and block is not None and not isinstance(front[block], list):
            if front[block] is None:
                front[block] = {}
            front[block][pair.group(2)] = scalar(pair.group(3) or "", where)
        else:
            sys.exit("error: %s: unsupported frontmatter line: %s" % (where, line))
    return front, text[match.end():]


def read_profiles(root):
    """Return {profile: (codex model, claude model)} from the table of model-profiles.md."""
    path = os.path.join(root, PROFILES)
    if not os.path.isfile(path):
        sys.exit("error: missing %s" % PROFILES)
    profiles, header = {}, False
    with open(path) as fh:
        for line in fh:
            if not line.lstrip().startswith("|"):
                header = False
                continue
            cells = [c.strip().strip("`") for c in line.strip().strip("|").split("|")]
            if cells == PROFILE_COLUMNS:
                header = True
            elif header and not all(set(c) <= set("-: ") for c in cells):
                if len(cells) != 3 or not all(cells):
                    sys.exit("error: %s: invalid profile row: %s" % (PROFILES, line.strip()))
                profiles[cells[0]] = (cells[1], cells[2])
    if not profiles:
        sys.exit("error: %s: no table with the columns %s" % (PROFILES, " | ".join(PROFILE_COLUMNS)))
    return profiles


def framework_skills(root):
    return sorted(os.path.basename(os.path.dirname(p))
                  for p in glob.glob(os.path.join(root, ".agents", "skills", "*", "SKILL.md")))


def body_skills(body, known):
    """Return the framework skills named in the body's `# Skills` section, or None without one."""
    match = re.search(r"^# Skills[ \t]*\n(.*?)(?=^# |\Z)", body, re.S | re.M)
    if not match:
        return None
    return sorted(s for s in known
                  if re.search(r"(?<![\w-])%s(?![\w-])" % re.escape(s), match.group(1)))


def check_source(front, body, path, profiles, known):
    for block, keys in FIELDS.items():
        fields = front if block is None else front.get(block)
        label = "" if block is None else block + "."
        if not isinstance(fields, dict):
            sys.exit("error: %s: `%s` must be a mapping" % (path, block))
        for key in keys:
            if key not in fields or (key != "skills" and not fields[key]):
                sys.exit("error: %s: missing %s%s" % (path, label, key))
        for key in sorted(set(fields) - set(keys)):
            sys.exit("error: %s: unknown field %s%s" % (path, label, key))
    name = front["name"]
    if not re.match(r"^[a-z0-9]+(-[a-z0-9]+)*$", name):
        sys.exit("error: %s: name must be lowercase and hyphenated: %s" % (path, name))
    if os.path.basename(path) != name + ".md":
        sys.exit("error: %s: file name does not match name %s" % (path, name))
    if front["profile"] not in profiles:
        sys.exit("error: %s: profile %s is not in %s (%s)"
                 % (path, front["profile"], PROFILES, ", ".join(sorted(profiles))))
    if front["effort"] not in EFFORTS:
        sys.exit("error: %s: effort must be one of %s" % (path, ", ".join(EFFORTS)))
    skills = front["skills"] or []
    if not isinstance(skills, list):
        sys.exit("error: %s: `skills` must be a list" % path)
    unknown = sorted(set(skills) - set(known))
    if unknown:
        sys.exit("error: %s: skills not in .agents/skills: %s" % (path, ", ".join(unknown)))
    named = body_skills(body, known)
    if named is None:
        sys.exit("error: %s: no `# Skills` section" % path)
    if named != sorted(set(skills)):
        sys.exit("error: %s: `skills` differ from the skills named in `# Skills`: only in the "
                 "frontmatter: %s; only in the section: %s"
                 % (path, ", ".join(sorted(set(skills) - set(named))) or "none",
                    ", ".join(sorted(set(named) - set(skills))) or "none"))
    front["skills"] = skills


def yaml_scalar(text):
    """Return text as a YAML plain scalar when it is safe, otherwise double-quoted."""
    if re.search(r": | #|^[-?:,\[\]{}#&*!|>'\"%@`]|^\s|\s$", text):
        return json.dumps(text)
    return text


def toml_string(text):
    return json.dumps(text, ensure_ascii=False)


def toml_multiline(text):
    """Return text as the content of a TOML multi-line basic string."""
    return text.replace("\\", "\\\\").replace('"""', '""\\"')


def claude_agent(front, body, profiles):
    # The Claude Code `skills` field preloads skills and does not restrict them, so the allowed
    # skills live only in the body's Skills section.
    return "\n".join([
        "---",
        "name: %s" % front["name"],
        "description: %s" % yaml_scalar(front["description"]),
        "model: %s" % profiles[front["profile"]][1],
        "effort: %s" % front["effort"],
        "tools: %s" % front["claude"]["tools"],
        "---",
        "",
    ]) + body


def codex_agent(front, body, profiles, known):
    lines = [
        # Codex identifies an agent by this field; the agents keep the underscore form that
        # Codex's own examples use.
        "name = %s" % toml_string(front["name"].replace("-", "_")),
        "description = %s" % toml_string(front["description"]),
        "model = %s" % toml_string(profiles[front["profile"]][0]),
        "model_reasoning_effort = %s" % toml_string(front["effort"]),
        "sandbox_mode = %s" % toml_string(front["codex"]["sandbox_mode"]),
        "",
        'developer_instructions = """',
        toml_multiline(body) + '"""',
    ]
    for skill in known:
        if skill not in front["skills"]:
            lines += ["", "[[skills.config]]",
                      "path = %s" % toml_string(".agents/skills/%s/SKILL.md" % skill),
                      "enabled = false"]
    return "\n".join(lines) + "\n"


def first_sentence(path):
    """Return the first sentence of the first paragraph after the title, without links."""
    with open(path) as fh:
        text = fh.read()
    paragraphs = [p for p in re.split(r"\n\s*\n", text) if p.strip()]
    for paragraph in paragraphs:
        if not paragraph.lstrip().startswith("#"):
            break
    else:
        return ""
    paragraph = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", " ".join(paragraph.split()))
    return re.split(r"(?<=[.!?])\s+(?=[A-Z`])", paragraph, 1)[0]


def catalog(root, agents):
    def link(rel):
        return "../" + rel.replace(os.sep, "/")

    lines = [CATALOG_MARK, "", "# Catalog", "",
             "Agents, skills, templates, and references of `.agents/`, generated from the",
             "`description` of each agent and skill and the first sentence of each template and",
             "reference. Regenerate it with `python3 .agents/scripts/generate_agents.py`.", "",
             "## Agents", "",
             "An agent's profile sets its model in each environment, as",
             "[model-profiles.md](%s) defines it;" % link(PROFILES),
             "Skills lists the framework skills that the agent may use.", "",
             "| Agent | Profile | Skills | Description |", "| --- | --- | --- | --- |"]
    for rel, front in agents:
        skills = ", ".join("`%s`" % s for s in front["skills"]) or "none"
        lines.append("| [`%s`](%s) | `%s` | %s | %s |"
                     % (front["name"], link(rel), front["profile"], skills, front["description"]))
    lines += ["", "## Skills", "", "| Skill | Description |", "| --- | --- |"]
    for path in sorted(glob.glob(os.path.join(root, ".agents", "skills", "*", "SKILL.md"))):
        front, _ = parse_front(path)
        rel = os.path.relpath(path, root)
        lines.append("| [`%s`](%s) | %s |" % (front.get("name"), link(rel), front.get("description")))
    references = os.path.join(root, ".agents", "references")
    templates = os.path.join(references, "templates")
    for title, base in (("Templates", templates), ("References", references)):
        lines += ["", "## %s" % title, "", "| File | Description |", "| --- | --- |"]
        paths = sorted(glob.glob(os.path.join(base, "*.md")) + glob.glob(os.path.join(base, "*", "*.md")))
        if base == references:
            paths = [p for p in paths if os.path.dirname(p) != templates]
        for path in paths:
            rel = os.path.relpath(path, root)
            lines.append("| [`%s`](%s) | %s |" % (os.path.relpath(path, base).replace(os.sep, "/"),
                                                   link(rel), first_sentence(path)))
    return "\n".join(lines) + "\n"


def main():
    args = sys.argv[1:]
    if any(a in ("-h", "--help") for a in args):
        print(USAGE)
        return 0
    check = "--check" in args
    want_catalog = "--catalog" in args
    rest = [a for a in args if a not in ("--check", "--catalog")]
    if any(a.startswith("-") for a in rest) or len(rest) > 1:
        sys.exit(USAGE)
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.abspath(rest[0]) if rest else os.path.dirname(os.path.dirname(here))
    sources = sorted(glob.glob(os.path.join(root, ".agents", "agents", "*.md")))
    if not sources:
        sys.exit("error: no agent sources in %s" % os.path.join(root, ".agents", "agents"))
    profiles = read_profiles(root)
    known = framework_skills(root)

    outputs, agents = {}, []
    for path in sources:
        front, body = parse_front(path)
        check_source(front, body, path, profiles, known)
        name = front["name"]
        outputs[os.path.join(".claude", "agents", name + ".md")] = claude_agent(front, body, profiles)
        outputs[os.path.join(".codex", "agents", name + ".toml")] = codex_agent(front, body, profiles, known)
        agents.append((os.path.relpath(path, root), front))
    catalog_path = os.path.join(root, CATALOG)
    if not want_catalog and os.path.isfile(catalog_path):
        with open(catalog_path) as fh:
            want_catalog = fh.readline().rstrip("\n") == CATALOG_MARK
    if want_catalog:
        outputs[CATALOG] = catalog(root, agents)

    changed = []
    for rel, content in sorted(outputs.items()):
        path = os.path.join(root, rel)
        current = None
        if os.path.isfile(path):
            with open(path) as fh:
                current = fh.read()
        if current == content:
            continue
        changed.append(rel)
        if not check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w") as fh:
                fh.write(content)
    for pattern in (os.path.join(".claude", "agents", "*.md"), os.path.join(".codex", "agents", "*.toml")):
        for path in sorted(glob.glob(os.path.join(root, pattern))):
            rel = os.path.relpath(path, root)
            if rel not in outputs:
                print("no source, not changed: %s" % rel)
    for rel in changed:
        print("%s: %s" % ("would change" if check else "written", rel))
    if not changed:
        print("up to date: %d agents%s" % (len(sources), " and the catalog" if want_catalog else ""))
    return 1 if check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
